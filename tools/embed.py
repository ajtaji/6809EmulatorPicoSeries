"""Turn a refgen vector file into a PureMetal DataSection include.

  py -3 tools/embed.py Diagnostics/v0.bin Diagnostics/vectors_a.pico <first_case>
"""
import sys
from pathlib import Path
src, dst, first = Path(sys.argv[1]), Path(sys.argv[2]), int(sys.argv[3])
data = src.read_bytes()
if not data.endswith(b'\x80'):
    raise SystemExit(f'{src}: no end marker; regenerate it')
lines = [f'; Generated by tools/embed.py from {src.name} ({len(data)} bytes). Expected states from XRoar\'s MC6809.',
         '; The first four bytes are the number of the first case, big-endian.', 'DataSection', 'Vectors:']
data = first.to_bytes(4, 'big') + data
for i in range(0, len(data), 32):
    lines.append('  Data.a ' + ','.join(f'${b:02X}' for b in data[i:i + 32]))
lines.append('EndDataSection')
dst.write_text('\n'.join(lines) + '\n')
print(dst, len(data), 'bytes')
