"""Write the per-chip verification wrappers (Diagnostics/verify-<config>-<batch>.<ext>).

  py -3 tools/make_wrappers.py
"""
from pathlib import Path

root = Path(__file__).resolve().parents[1] / 'Diagnostics'
CHIPS = {'picow': ('RP2040', 'pico', 200000), 'pico2w': ('RP2350', 'pico2', 150000)}
CONFIGS = {'timed': (1, 1), 'fast': (0, 1), 'pure': (1, 0)}
for ext, (lib, cext, khz) in CHIPS.items():
    for cfg, (timing, tail) in CONFIGS.items():
        for batch in 'bcdi':
            lines = [f'; Generated by tools/make_wrappers.py: {cfg} build, vector batch {batch}, {lib}.',
                     f'#CLOCK_KHZ = {khz}', f'#CPU_TIMING = {timing}', f'#CPU_ASM_TAIL = {tail}', 'EnableExplicit']
            lines += [f'XIncludeFile "{lib}/Lib/{m}.{cext}"' for m in ('clocks', 'timer', 'uart', 'usb_serial', 'safety')]
            lines += [f'XIncludeFile "../src/cpu6809.{cext}"', f'XIncludeFile "../src/io.{cext}"',
                      'XIncludeFile "verify_body.pmi"', f'XIncludeFile "vectors_{batch}.pmi"',
                      'XIncludeFile "schwotzer_data.pmi"']
            (root / f'verify-{cfg}-{batch}.{ext}').write_text('\n'.join(lines) + '\n')
print('wrappers written')
