"""Turn an asm6809 S-record file into a PureMetal DataSection of segments:
address(2) length(2) bytes..., ended by a zero length.

  py -3 tools/embed_srec.py Diagnostics/schwotzer.s19 Diagnostics/schwotzer_data.pmi Schwotzer
"""
import sys
from pathlib import Path
src, dst, label = Path(sys.argv[1]), Path(sys.argv[2]), sys.argv[3]
mem = {}
for line in src.read_text().split():
    if line.startswith('S1'):
        n = int(line[2:4], 16)
        raw = bytes.fromhex(line[2:2 + 2 * (n + 1)])
        if sum(raw) & 255 != 255:
            raise SystemExit(f'checksum error: {line}')
        addr = int(line[4:8], 16)
        for i, b in enumerate(bytes.fromhex(line[8:2 + 2 * n])):
            mem[addr + i] = b
segs, cur = [], None
for a in sorted(mem):
    if cur and a == cur[0] + len(cur[1]):
        cur[1].append(mem[a])
    else:
        cur = [a, [mem[a]]]
        segs.append(cur)
out = bytearray()
for a, d in segs:
    out += a.to_bytes(2, 'big') + len(d).to_bytes(2, 'big') + bytes(d)
out += b'\0\0\0\0'
lines = [f'; Generated by tools/embed_srec.py from {src.name}: {len(segs)} segments, {len(mem)} bytes.',
         'DataSection', f'{label}:']
for i in range(0, len(out), 32):
    lines.append('  Data.a ' + ','.join(f'${b:02X}' for b in out[i:i + 32]))
lines.append('EndDataSection')
dst.write_text('\n'.join(lines) + '\n')
print(dst, len(segs), 'segments', len(mem), 'bytes')
